// Generates byte codes and literals for one method, as used by the parse tree nodes in SmallNodes.
// The byte codes must match the operations in SmallInterpreter.

import java.util.ArrayList;
import java.util.List;

class SmallEncoder
{
	SmallImage image;
	String name;
	List< Integer > byteCodes = new ArrayList<>();
	List< SmallObject > literals = new ArrayList<>();
	int stackSize = 0;
	int maxStack = 1;

	SmallEncoder( SmallImage aImage, String aName )
	{
		image = aImage;
		name = aName;
	}

	SmallObject newString( String value )
	{
		return new SmallByteArray( image.stringClass, value );
	}

	void backUp()
	{
		byteCodes.remove( byteCodes.size() - 1 );
	}

	int currentLocation()
	{
		return byteCodes.size();
	}

	// Returns 1-based location of the generated byte, for patch().

	int genCode( int code )
	{
		byteCodes.add( code );
		return byteCodes.size();
	}

	void genHigh( int high, int low )
	{
		if( low >= 16 ) {
			genHigh( 0, high );
			genCode( low );
		} else {
			genCode( high * 16 + low );
		}
	}

	int genLiteral( SmallObject value )
	{
		literals.add( value );
		return literals.size() - 1;
	}

	// Patch a goto location.

	void patch( int location )
	{
		byteCodes.set( location - 1, currentLocation() );
	}

	void pushArgs( int count )
	{
		stackSize += count;
		maxStack = Math.max( stackSize, maxStack );
	}

	void popArgs( int count )
	{
		stackSize -= count;
	}

	SmallCompiler.CompiledMethod method( int maxTemps )
	{
		byte[] codes = new byte[ byteCodes.size() ];
		for( int i = 0; i < codes.length; i++ )
			codes[ i ] = ( byte ) ( int ) byteCodes.get( i );
		// Stack size doesn't take primitives into account. Minimum 20 supports primitives with up to 20 args.
		return new SmallCompiler.CompiledMethod( name, codes, literals, Math.max( maxStack + 5, 20 ), maxTemps );
	}
}
